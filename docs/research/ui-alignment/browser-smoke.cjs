const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.STELE_TEST_URL || 'http://localhost:5173/');
 await page.getByRole('heading',{name:/Know what governs/}).waitFor();
 await page.getByRole('button',{name:'Verify local chain'}).click();
 await page.getByRole('status').filter({hasText:/ZANSHIN.*entries checked/}).waitFor();
 const downloadPromise=page.waitForEvent('download'); await page.getByRole('button',{name:'Export audit JSON'}).click();
 const download=await downloadPromise; const audit=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 if(audit.currentState!=='ZANSHIN'||!audit.entries.length)throw Error('audit export incomplete');
 await page.screenshot({path:process.env.STELE_DESKTOP_SCREENSHOT || '/tmp/stele-session-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Modes',exact:true}).click();
 await page.getByRole('textbox',{name:'Mode name',exact:true}).fill('Release review');
 await page.getByRole('button',{name:'Create and select mode'}).click();
 await page.getByRole('heading',{name:'Edit Release review'}).waitFor();
 await page.getByRole('combobox',{name:'Mode verbosity'}).selectOption('expanded');
 await page.getByRole('checkbox',{name:'Code',exact:true}).uncheck();
 if(await page.getByRole('checkbox',{name:'Code',exact:true}).isChecked())throw Error('section not updated');
 await page.getByRole('button',{name:'Delete Release review',exact:true}).click();
  if(await page.getByRole('button',{name:'Delete BUILD',exact:true}).count())throw Error('built-in delete exposed');
 await page.getByRole('button',{name:'Session',exact:true}).click();
 await page.getByRole('heading',{name:'BUILD · standard'}).waitFor();
 await page.setViewportSize({width:820,height:1000});
 await page.getByRole('button',{name:/Levers$/}).click();
 await page.getByRole('heading',{name:/Know what governs/}).waitFor();
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('mobile overflow');
 await page.screenshot({path:process.env.STELE_MOBILE_SCREENSHOT || '/tmp/stele-session-mobile.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({desktop:'passed',mobile:'passed',modeAuthoring:'passed',auditExportEntries:audit.entries.length,pageErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
